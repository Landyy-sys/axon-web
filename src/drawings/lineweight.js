/* 三级绝对线宽，不再由各视图基线宽 b 派生标注与轴线：
   CUT     3.0  剖切轮廓线 —— 平/剖面中被剖到的墙体（poché 边界）
   VISIBLE 1.5  未剖切轮廓线 —— 门窗、台阶、立面可见轮廓
   DIM     0.5  尺寸标注线、引出线、轴线（细点划线）
   FRAME   1.4  图框线（A3 图框内框，稍粗于一般轮廓） */
export const LINE_W = { CUT: 3, VISIBLE: 1.5, DIM: 0.5, FRAME: 1.4 }

/* 填充纹理线宽上限：poché / 地坪填充属「最细线」级，
   基线宽放大（剖切图 b=3）时必须封顶，否则斜线糊成一团 */
export const hatchW = (w, cap = 0.8) => Math.min(w, cap)
