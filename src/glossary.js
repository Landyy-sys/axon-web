export const GLOSSARY_GROUPS = ['尺寸', '构件', '制图', '方法']

export function searchGlossary(q) {
  const s = (q || '').trim().toLowerCase()
  if (!s) return GLOSSARY
  return GLOSSARY.filter(
    (t) =>
      t.term.toLowerCase().includes(s) ||
      (t.alias || '').toLowerCase().includes(s) ||
      t.plain.toLowerCase().includes(s) ||
      t.pro.toLowerCase().includes(s),
  )
}
